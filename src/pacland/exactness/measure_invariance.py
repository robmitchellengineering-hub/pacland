"""Which of our results survive ANY choice of measure?

Albert [01:39:47]: *"Any probability distribution whatsoever over classical initial conditions is perfectly logically
compatible with the classical equations of motion."* Carroll [01:37:27]: on parameters and laws there is no measure to
derive. So a result that depends on which measure is stipulated is **not truth-apt** — it is a report about a
convention.

This module is the audit: every recorded result is classed as

    INVARIANT  — true whatever measure is chosen (usually because it is a theorem or an exact count)
    DEPENDENT  — true only relative to a stipulated measure or corpus selection

and the classes are published as a generated register so neither can drift silently.

Regenerate:  python3 scripts/measure_audit.py
Verify:      python3 scripts/measure_audit.py --check
Guarded by:  tests/test_measure_invariance.py
"""
from __future__ import annotations

#: (name, class, why, module)
REGISTER = (
    ("max |N| = b3", "INVARIANT",
     "a theorem about the pairing, not a statistic over anything",
     "exactness/tadpole_bound.py"),
    ("conifold coefficients 37/30, 2309/1800", "INVARIANT",
     "exact rationals; no weighting enters",
     "periods/conifold_recursion.py"),
    ("zeta zeros to 6.4e-13", "INVARIANT",
     "agreement with known values; a property of the spectrum, not of a weighting",
     "spectral/zeros.py"),
    ("content law A = 8.554", "INVARIANT",
     "from exact orbit counts in a fully enumerated window; no sampling",
     "exactness/b3_scaling.py"),
    ("gauge quotient: 1 orbit in 531,441", "INVARIANT",
     "an exact count over the enumerated window",
     "exactness/landscape_count.py"),
    ("arithmetic rigidity: zeros 0.617 vs GOE 0.531", "INVARIANT",
     "a property of the spectrum itself; the random control validates the statistic",
     "spectral/arithmetic_stats.py"),
    ("mass spectra are Poisson at every b3", "DEPENDENT",
     "computed over the sampled corpus, so it inherits the corpus selection",
     "spectral/arithmetic_stats.py"),
    ("SUSY fraction 0.279 / 0.202 / 0.012 by b3", "DEPENDENT",
     "a fraction over a sampled corpus; a different corpus selection moves it",
     "exactness/counterexample.py"),
    ("the N/b3 ratio collapse and its break at b3 = 10", "DEPENDENT",
     "same corpus dependence as the fraction it organises",
     "exactness/counterexample.py"),
    ("measure-dependence 5.05x (21% vs 1%)", "DEPENDENT",
     "it IS the measure dependence; reporting the spread is the point",
     "exactness/robustness.py"),
    ("accessibility series 0.1325 -> 0.00137 -> 0.0151", "DEPENDENT",
     "a sampler observable with n_batch/max_batches budgets; demoted in the well-posedness reply",
     "exactness/b3_scaling.py"),
    ("the b3 = 6 yield 0.1325/try", "DEPENDENT",
     "an n_target = 20 cap artefact, not a rate",
     "exactness/b3_scaling.py"),
)


def by_class() -> dict:
    out = {"INVARIANT": [], "DEPENDENT": []}
    for name, cls, why, module in REGISTER:
        out[cls].append({"name": name, "why": why, "module": module})
    return out


def counts() -> dict:
    c = by_class()
    return {"invariant": len(c["INVARIANT"]), "dependent": len(c["DEPENDENT"]), "total": len(REGISTER)}


def render() -> str:
    c = counts()
    lines = [
        "# The measure-invariance audit",
        "",
        "Generated by `python3 scripts/measure_audit.py`. **Do not edit by hand.**",
        "",
        "Albert [01:39:47]: any distribution is logically compatible with the equations of motion, so a result that",
        "depends on a stipulated measure is not truth-apt. Carroll [01:37:27]: for parameters and laws no measure is",
        "derived. This register therefore splits every recorded result in two.",
        "",
        f"**{c['invariant']} invariant · {c['dependent']} dependent · {c['total']} total**",
        "",
        "## INVARIANT — true whatever measure is chosen",
        "",
    ]
    for r in by_class()["INVARIANT"]:
        lines += [f"- **{r['name']}** — {r['why']}  ", f"  `{r['module']}`"]
    lines += ["", "## DEPENDENT — true only relative to a stipulated measure or corpus selection", ""]
    for r in by_class()["DEPENDENT"]:
        lines += [f"- **{r['name']}** — {r['why']}  ", f"  `{r['module']}`"]
    lines += ["", "A DEPENDENT result is not withdrawn; it must be quoted with its measure or corpus attached."]
    return "\n".join(lines) + "\n"


__all__ = ["REGISTER", "by_class", "counts", "render"]
