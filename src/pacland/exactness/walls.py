"""Every place the programme gets stuck, classified by whose wall it is.

Two days were spent treating a work-budget artefact as a law of nature, and months treating a provable
underdetermination as a failure to find the right measure. Both cost real time for the same reason: **nothing recorded
which walls had already been classified.**

So each wall carries one of four classes:

    DISSOLVES        gone with more work or a bigger budget -- it was our instrument
    PROVABLE         a theorem that the obstruction cannot be removed -- a constraint on the theory
    INFRASTRUCTURE   a library or data gap -- says nothing about physics
    BOUNDED          a real negative with a stated domain, not a failure

**Only PROVABLE walls constrain a unification.** A DISSOLVES wall is a measurement error wearing a law's clothes.

Regenerate:  python3 scripts/walls.py
Verify:      python3 scripts/walls.py --check
Guarded by:  tests/test_walls.py
"""
