def by_class() -> dict:
    out = {"DISSOLVES": [], "PROVABLE": [], "INFRASTRUCTURE": [], "BOUNDED": []}
    for name, cls, looked, actually, evidence in REGISTER:
        out[cls].append({"name": name, "looked_like": looked, "actually": actually, "evidence": evidence})
    return out


def counts() -> dict:
    c = by_class()
    return {k.lower(): len(v) for k, v in c.items()} | {"total": len(REGISTER)}


def render() -> str:
    c = counts()
    lines = [
        "# The wall register",
        "",
        "Generated by `python3 scripts/walls.py`. **Do not edit by hand.**",
        "",
        "Every place the programme gets stuck, classified by **whose wall it is**. Two days went into treating a work",
        "budget as a law of nature; months went into treating a provable underdetermination as a missing measure.",
        "Nothing recorded which walls had already been classified, so each was re-litigated.",
        "",
        f"**{c['dissolves']} dissolve · {c['provable']} provable · {c['infrastructure']} infrastructure · "
        f"{c['bounded']} bounded · {c['total']} total**",
        "",
        "**Only PROVABLE walls constrain a unification.** A dissolving wall is a measurement error wearing a law's",
        "clothes.",
        "",
    ]
    order = [
        ("PROVABLE", "PROVABLE — a constraint on the theory"),
        ("BOUNDED", "BOUNDED — a real negative with a stated domain"),
        ("DISSOLVES", "DISSOLVES — it was our instrument"),
        ("INFRASTRUCTURE", "INFRASTRUCTURE — a gap in a library, not in physics"),
    ]
    for key, title in order:
        lines += [f"## {title}", ""]
        for r in by_class()[key]:
            lines += [f"### {r['name']}", "",
                      f"- **looked like:** {r['looked_like']}",
                      f"- **actually is:** {r['actually']}",
                      f"- **evidence:** {r['evidence']}", ""]
    return "\n".join(lines) + "\n"


