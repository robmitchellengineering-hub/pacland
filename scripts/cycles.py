def render(loops) -> str:
    out = ["# Cycles — the no → question → yes → no loop, closed ones only",
           "",
           "*Generated by `python3 scripts/cycles.py`. Each entry is one turn: a negative, the question it "
           "forced, the object or definition that answered it, and **what it excluded**. An entry with no "
           "exclusion is maintenance, not a turn, and does not belong here.*",
           "",
           f"**{len(loops)} closed loops.**"]
    for c in loops:
        out += [f"## {c['id']}", "",
                f"**No.** {c['negative']}", "",
                f"**Question.** {c['question']}", "",
                f"**Object / answer.** {c['object']}", "",
                f"**Excluded.** {c['excluded']}", "",
                f"*reproduce:* `{c['command']}`", ""]
    return "\n".join(out)


def main() -> int:
    text = render(LOOPS)
    if "--check" in sys.argv:
        if not OUT.exists():
            print(f"MISSING: {OUT}")
            return 1
        if OUT.read_text() != text:
            print("STALE: docs/cycles.md does not match a fresh generation")
            return 1
        print("current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
