#!/usr/bin/env python3
"""Mitchell's uniqueness theorem, at scale — the full symplectic algebra, and more than one flux pair.

The existing validator (`validate_mitchell_uniqueness.py`) proves the claim for one flux pair using a
shear subgroup. Two questions are left open, and this script settles both by linear algebra:

  Q1  Does the uniqueness hold against the FULL symplectic algebra sp(2m), for several b3?
  Q2  Does it survive a SECOND, independent flux pair — which real compactifications can have?

The invariant bilinear forms are the nullspace of `G^T A + A G = 0` stacked over a basis of sp(2m).
That is exact linear algebra, not a sampled subgroup, so an answer of "1" here is a real count.

Run:  python3 scripts/validate_uniqueness_at_scale.py
"""
import sys

import numpy as np


def sp_basis(m: int) -> list[np.ndarray]:
    """A basis of the symplectic Lie algebra sp(2m): [[A, B], [C, -A^T]], B and C symmetric."""
    out = []
    for i in range(m):
        for j in range(m):
            g = np.zeros((2 * m, 2 * m))
            g[i, j] = 1.0
            g[m + j, m + i] = -1.0
            out.append(g)
    for i in range(m):
        for j in range(i, m):
            g = np.zeros((2 * m, 2 * m))
            g[i, m + j] = 1.0
            g[j, m + i] = 1.0
            out.append(g)
            g = np.zeros((2 * m, 2 * m))
            g[m + i, j] = 1.0
            g[m + j, i] = 1.0
            out.append(g)
    return out


def invariant_bilinear_forms(m: int, pairs: int = 1) -> dict:
    """Count the independent invariant forms sum_{p,q} F_p^T A_{pq} H_q, under (F, H) -> (S F, S H)."""
    n = 2 * m
    blocks = pairs * pairs
    rows = []
    for g in sp_basis(m):
        for p in range(pairs):
            for q in range(pairs):
                base = (p * pairs + q) * n * n
                for a in range(n):
                    for b in range(n):
                        row = np.zeros(blocks * n * n)
                        for i in range(n):
                            row[base + i * n + b] += g[i, a]     # (G^T A)_{ab}
                            row[base + a * n + i] += g[i, b]     # (A G)_{ab}
                        rows.append(row)
    A = np.asarray(rows)
    sv = np.linalg.svd(A, compute_uv=False)
    tol = 1e-9 * max(sv[0], 1.0)
    rank = int(np.sum(sv > tol))
    return {"m": m, "b3": 2 * m, "pairs": pairs,
            "invariants": blocks * n * n - rank, "entries": blocks * n * n,
            "algebra_dim": len(sp_basis(m))}


def main() -> int:
    print("Mitchell's uniqueness theorem, at scale\n")
    print("Q1  one flux pair, full sp(2m) — the theorem's own case:")
    ok = True
    for m in (1, 2, 3):
        r = invariant_bilinear_forms(m, 1)
        good = r["invariants"] == 1
        ok = ok and good
        print(f"   b3={r['b3']:2}  algebra dim {r['algebra_dim']:2}  "
              f"invariant forms: {r['invariants']}   {'PASS' if good else 'FAIL'}")
    print("\nQ2  two independent flux pairs — beyond the theorem's stated scope:")
    for m in (1, 2, 3):
        r = invariant_bilinear_forms(m, 2)
        print(f"   b3={r['b3']:2}  invariant forms: {r['invariants']}  "
              f"(F_p^T J H_q for p, q in 1..2)")
    print()
    print("Reading:")
    print("  Q1 answers 1 for every b3 tested, now against the FULL symplectic algebra rather than a")
    print("     shear subgroup. The uniqueness theorem is confirmed, not merely reproduced.")
    print("  Q2 answers 4: with a second independent flux sector there are three ADDITIONAL exact")
    print("     invariants — the cross-tadpoles F_1^T J H_2 and F_2^T J H_1, and the second sector's")
    print("     own F_2^T J H_2. So 'the D3 tadpole is the unique exact structure' is a statement")
    print("     about ONE symplectic pair, and its scope has to say so.")
    print()
    print("  NOT computed here: higher-degree (quartic, sextic) invariants. The first fundamental")
    print("  theorem for Sp says they are generated by the bilinear ones, which is why no new exact")
    print("  observable is expected — but that is REASONED from a standard theorem, not computed, and")
    print("  it is labelled as such rather than presented as a measurement.")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
