#!/usr/bin/env python3
"""Auto-generate the live climate page — same pattern as make_explainers.py.

Reads the climate modules (not hand-written prose), so the page is a live
reflection of the work: re-run after any climate change and the site picks up
the new numbers on the next deploy.

    python3 scripts/make_site.py

Outputs web/climate.html (linked from web/index.html).
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from pacland.climate import trust_board
from pacland.climate.deficit import climate_deficit_report
from pacland.climate.drift_correction import (
    correction_proof,
    correction_proof_all,
    repair_report,
    retrospective,
)
from pacland.climate.ecs_model import ecs_estimates

ROOT = Path(__file__).resolve().parents[1]


def _f(x: float, p: int = 2) -> str:
    return f"{x:+.{p}f}"


def build() -> str:
    hist, proj = climate_deficit_report()
    rp = repair_report()
    cpa = correction_proof_all()
    rx = retrospective()
    cp = correction_proof("HadGEM3-GC31-LL")
    tb = trust_board.board()
    trusted = [m for m in tb if len(m["axes_failed"]) == 0 and m["axes_available"] == 3]
    n_trusted = len(trusted)

    drift_rows = "\n".join(
        f"<tr><td>{m['model']}</td><td class='num'>{m['before_netTOA_Wm2']:+.3f}</td>"
        f"<td class='num'>0.000</td><td class='num'>{m['imbalance_removed_K']:.2f} K</td></tr>"
        for m in sorted(cpa["models"], key=lambda x: -abs(x["before_netTOA_Wm2"]))
    )

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>PACLAND · Climate — live</title>
<meta name="description" content="The PACLAND climate discipline, live: the verification deficit, the CMIP6 conservation leak, the drift-correction fix, and the retrospective test — generated from the current data.">
<style>
  :root {{ --ink:#1a1f2e; --muted:#5a6072; --accent:#142a5e; --line:#e3e6ee; --bg:#fbfbfd; }}
  * {{ box-sizing:border-box; }}
  body {{ margin:0; font-family:-apple-system,"Segoe UI",Roboto,Helvetica,Arial,sans-serif; color:var(--ink); background:var(--bg); line-height:1.6; }}
  header {{ background:var(--accent); color:#fff; padding:3rem 1.5rem 2.2rem; }}
  header .wrap, main .wrap {{ max-width:860px; margin:0 auto; padding:0 1.5rem; }}
  header h1 {{ margin:0 0 .4rem; font-size:2rem; }}
  header .sub {{ color:#c7d2ee; }}
  header .gen {{ margin-top:1rem; font-size:.78rem; color:#9fb0d8; }}
  main {{ padding:2.4rem 0 4rem; }}
  h2 {{ color:var(--accent); margin:2.2rem 0 .5rem; font-size:1.35rem; }}
  .grid {{ display:grid; grid-template-columns:repeat(auto-fit,minmax(240px,1fr)); gap:1rem; margin:1rem 0; }}
  .card {{ border:1px solid var(--line); border-radius:10px; padding:1rem 1.1rem; background:#fff; }}
  .card .big {{ font-size:1.5rem; font-weight:700; color:var(--accent); }}
  .card p {{ margin:.3rem 0 0; font-size:.92rem; color:var(--muted); }}
  table {{ border-collapse:collapse; width:100%; margin:1rem 0; background:#fff; }}
  th, td {{ text-align:left; padding:.5rem .7rem; border-bottom:1px solid var(--line); font-size:.92rem; }}
  th {{ background:#f4f6fa; color:var(--accent); }}
  td.num {{ text-align:right; font-variant-numeric:tabular-nums; }}
  .callout {{ border-left:4px solid var(--accent); background:#eef1f8; padding:.9rem 1.1rem; border-radius:0 8px 8px 0; margin:1.2rem 0; }}
  .muted {{ color:var(--muted); font-size:.9rem; }}
  a {{ color:var(--accent); }}
  footer {{ border-top:1px solid var(--line); padding:1.5rem; text-align:center; color:var(--muted); font-size:.85rem; }}
</style>
</head>
<body>
<header><div class="wrap">
  <h1>PACLAND · Climate</h1>
  <div class="sub">The verification discipline applied to climate modelling — a live page, generated from the current data.</div>
  <div class="gen">generated by <code>scripts/make_site.py</code> from <code>pacland.climate</code> · re-run to refresh · <a style="color:#fff" href="PACLAND-climate-3d.html">open the 3D graphs</a></div>
</div></header>
<main><div class="wrap">

<h2>Headlines</h2>
<div class="grid">
  <div class="card"><h3>Verification deficit</h3><div class="big">m = {hist.n_validation} → {round(hist.radius*100)}% · m = {proj.n_validation}</div>
    <p>Only {hist.n_validation} historical observables are measured + computable + validated; the 2100 projection has m = {proj.n_validation} — extrapolation, not verification.</p></div>
  <div class="card"><h3>Conservation leak</h3><div class="big">{rp['n_leaking']} / {rp['n_models']} leak</div>
    <p>{rp['n_leaking']} models leak energy/mass/salt in their control run — localized to the atmosphere–ocean coupling, not the ocean.</p></div>
  <div class="card"><h3>The fix</h3><div class="big">{cpa['n_failed_before']} → {cpa['n_failed_after']} fail</div>
    <p>Drift-correction makes every model conserve: {cpa['n_failed_before']} fail conservation before, {cpa['n_failed_after']} after (max {cpa['max_imbalance_removed_K']:.2f} K removed).</p></div>
  <div class="card"><h3>Retrospective ECS</h3><div class="big">{rx['ecs_naive_K']:.2f} → {rx['ecs_sens_forc_gated_K']:.2f} K</div>
    <p>The gates land the ensemble at {rx['ecs_sens_forc_gated_K']:.2f} K ({_f(rx['ecs_corrected_bias_K'])} vs observed 3.0 K) — the naive {rx['ecs_naive_K']:.2f} K was {_f(rx['ecs_naive_bias_K'])} hot.</p></div>
</div>

<div class="callout"><p><strong>The most-used model, corrected.</strong> {cp['verdict']}</p></div>

<h2>The whole ensemble, corrected</h2>
<p class="muted">Every model's net-TOA leak, before → after drift-correction. The correction is the negated leak; every model conserves exactly afterward.</p>
<table><thead><tr><th>model</th><th>before (W/m²)</th><th>after (W/m²)</th><th>imbalance removed</th></tr></thead><tbody>
{drift_rows}
</tbody></table>

<h2>The retrospective — what the correction does and does not do</h2>
<div class="callout"><p>{rx['verdict']}</p></div>
<p class="muted">Separately: the drift-correction restores <strong>conservation</strong> (the First Law); the <strong>trust gate</strong> (sensitivity + forcing) fixes the hot-model temperature bias. Two different tools, now both measured.</p>

<h2>The trust gate</h2>
<p>{n_trusted} of {len(tb)} models pass all three axes (conservation + sensitivity + forcing). Interactive: <a href="PACLAND-climate-3d.html">the 3D graphs</a>.</p>

<p class="muted">Full findings: <a href="https://github.com/robmitchellengineering-hub/pacland/blob/main/docs/climate-repair.md">climate-repair.md</a> · <a href="https://github.com/robmitchellengineering-hub/pacland/blob/main/docs/climate-cmip6-drift.md">CMIP6 drift</a> · <a href="https://raw.githubusercontent.com/robmitchellengineering-hub/pacland/main/PACLAND-climate-explainer.pdf">explainer (PDF)</a>. Reproduce: <code>pacland climate</code> · <code>python3 scripts/make_site.py</code>.</p>

</div></main>
<footer>PACLAND · a verification discipline · generated live from <code>pacland.climate</code></footer>
</body>
</html>"""


def main() -> int:
    out = ROOT / "web" / "climate.html"
    out.write_text(build())
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
