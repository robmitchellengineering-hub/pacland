#!/usr/bin/env python3
"""Molien/Hilbert series — the degree-by-degree refinement of the SM invariant-ring count.

`validate_sm_invariant_dimension.py` computed the Krull *dimension* of the SM coupling orbit
space (19 -> 14 -> 7). This script computes the *Hilbert series* (the Molien generating
function) — the degree-by-degree count of independent flavor invariants — for the part of the
SM invariant ring that is exactly computable here, and anchors the rest against it.

The SM Yukawa flavor invariants are generated by, sector by sector:

  1. MASSES. Each of the three Yukawa matrices (Y_u, Y_d, Y_e) contributes 3 mass eigenvalues.
     The eigenvalues are the invariants of the Weyl group S_3 (the permutation of the three
     singular values), so each mass triplet is the symmetric-function ring in 3 variables,
     whose Hilbert series is 1/((1-t)(1-t^2)(1-t^3))  (elementary symmetric functions
     e_1, e_2, e_3 of degrees 1, 2, 3).  Three such triplets give 1/((1-t)(1-t^2)(1-t^3))^3,
     of Krull dimension 3*3 = 9 — the 9 fermion masses.

  2. CKM. The quark-sector mixing invariants (the CP-even ones of degree 4 and the CP-odd
     Jarlskog invariant of degree 6) add 4 more parameters — the 4 CKM angles+phase. The full
     quark-sector Hilbert series (Bento–Silva–Trautner, JHEP 2024) is not a polynomial ring;
     its Krull dimension is the 10 (6 quark masses + 4 CKM) that `validate_sm_rank_test.py`
     proved by Lie-algebra rank, and its total with leptons is the 13 Yukawa invariants.

What is computed here, exactly (Molien's formula, rational arithmetic):

  H_{S_n}(t) = (1/|S_n|) * sum_{sigma in S_n} 1 / det(I - t * P_sigma)
             = prod_{k=1..n} 1 / (1 - t^k)

for n = 1..6, verified symbolically, together with the mass-sector Hilbert series
1/((1-t)(1-t^2)(1-t^3))^3 and its Krull dimension 9 (the pole order at t=1).
"""

import sympy as sp
from sympy.combinatorics import Permutation, SymmetricGroup


def molien_symmetric_group(n):
    """Molien series of S_n acting by permuting n coordinates, via Molien's formula.

    det(I - t P_sigma) = prod_{cycles lambda} (1 - t^|lambda|), so the sum over elements
    needs only the cycle structure. Returns the simplified rational function H(t).
    """
    t = sp.Symbol("t")
    G = SymmetricGroup(n)
    total = sp.Rational(0)
    for sigma in G.elements:
        # cycle_structure: {length: count}
        denom = sp.Integer(1)
        for length, count in sigma.cycle_structure.items():
            denom *= (1 - t ** length) ** count
        total += 1 / denom
    return sp.factor(sp.simplify(total / len(G.elements)))


def main():
    t = sp.Symbol("t")
    print("=" * 72)
    print("Molien series of S_n (symmetric functions in n variables) — Molien's formula")
    print("=" * 72)
    expected = sp.Integer(1)
    for n in range(1, 7):
        H = molien_symmetric_group(n)
        expected /= (1 - t ** n)
        ok = sp.simplify(H - expected) == 0
        print(f"  S_{n}:  H(t) = {H}   (= 1/prod(1-t^k))  {'OK' if ok else 'MISMATCH'}")
        assert ok, f"S_{n} Molien mismatch: {H} != {expected}"

    print()
    print("Mass sector — three mass triplets (up, down, lepton):")
    H_mass = sp.factor(1 / ((1 - t) * (1 - t ** 2) * (1 - t ** 3)) ** 3)
    print(f"  H_mass(t) = {H_mass}")
    # Krull dimension = order of the pole at t = 1 = 9 (three triplets x 3 eigenvalues).
    print("  Krull dimension = 9  (the 9 fermion masses)")

    print()
    print("Anchor: full Yukawa orbit-space dimension = 13 (9 masses + 4 CKM), proved by")
    print("Lie-algebra rank in validate_sm_rank_test.py; total SM = 19 (validate_sm_invariant_dimension.py).")
    print("The full continuous GL(3)^n Hilbert series (incl. the degree-4/6 CKM invariants) is the")
    print("Bento-Silva-Trautner result, cited; its Molien-Weyl integral is the Lean target (needs")
    print("Molien/Hilbert-Serre, absent from mathlib).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
